import {afterEach, describe, expect, it, vi} from 'vitest';
import {extractUrls, generateSenderLinkPreviews, parseHtmlMetadata} from './ClientLinkPreviewUtils';

describe('ClientLinkPreviewUtils', () => {
	afterEach(() => {
		vi.restoreAllMocks();
	});

	it('extracts valid HTTP and HTTPS URLs and strips trailing punctuation', () => {
		const text =
			'Check out https://github.com/PJJunio/osaca! Also visit http://example.org, and https://test.dev/path?a=1&b=2.';
		const urls = extractUrls(text);
		expect(urls).toEqual(['https://github.com/PJJunio/osaca', 'http://example.org', 'https://test.dev/path?a=1&b=2']);
	});

	it('returns empty array when text has no URLs', () => {
		expect(extractUrls('Hello world, no links here')).toEqual([]);
		expect(extractUrls('')).toEqual([]);
	});

	it('parses HTML metadata including OpenGraph title, description, image, and site_name', () => {
		const html = `
			<!DOCTYPE html>
			<html>
				<head>
					<title>Fallback Title</title>
					<meta property="og:title" content="OpenGraph Example Title" />
					<meta property="og:description" content="This is an OpenGraph description with &amp; entities." />
					<meta property="og:site_name" content="Example Site" />
					<meta property="og:image" content="https://example.com/cover.png" />
				</head>
				<body></body>
			</html>
		`;
		const preview = parseHtmlMetadata(html, 'https://example.com/article');
		expect(preview).toEqual({
			url: 'https://example.com/article',
			title: 'OpenGraph Example Title',
			description: 'This is an OpenGraph description with & entities.',
			site_name: 'Example Site',
			image: {
				url: 'https://example.com/cover.png',
			},
		});
	});

	it('falls back to standard title and meta description when OpenGraph tags are missing', () => {
		const html = `
			<!DOCTYPE html>
			<html>
				<head>
					<title>Standard Page Title</title>
					<meta name="description" content="Standard page description" />
				</head>
				<body></body>
			</html>
		`;
		const preview = parseHtmlMetadata(html, 'https://example.com/page');
		expect(preview).toEqual({
			url: 'https://example.com/page',
			title: 'Standard Page Title',
			description: 'Standard page description',
		});
	});

	it('sender link previews is OFF by default (enabled=false) and generates no previews', async () => {
		const fetchSpy = vi.spyOn(globalThis, 'fetch');
		const previews = await generateSenderLinkPreviews('Visit https://example.com today!', {enabled: false});

		expect(previews).toEqual([]);
		expect(fetchSpy).not.toHaveBeenCalled();
	});

	it('fetches and generates previews when sender link previews is enabled', async () => {
		const fakeHtml = `
			<html>
				<head>
					<title>Opt-in Website</title>
					<meta property="og:description" content="Generated by sender client" />
				</head>
			</html>
		`;

		vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(
			new Response(fakeHtml, {
				status: 200,
				headers: {'content-type': 'text/html; charset=utf-8'},
			}),
		);

		const previews = await generateSenderLinkPreviews('Here is https://optin.test/link', {enabled: true});
		expect(previews).toHaveLength(1);
		expect(previews[0]).toEqual({
			url: 'https://optin.test/link',
			title: 'Opt-in Website',
			description: 'Generated by sender client',
		});
	});
});
