// Renders osaca_static/badges/<kind>.svg into the 128x128 PNG and WebP files the API serves,
// names them by content hash, and updates the badge manifest and ProfileBadgeAssets.ts.
// Usage (repository root): node tools/branding/render-profile-badges.mjs
// sharp comes from the osaca_docs workspace package.

import {createHash} from 'node:crypto';
import {existsSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';

const repoRoot = new URL('../../', import.meta.url);
const badgesDir = new URL('osaca_static/badges/', repoRoot);
const assetsFile = new URL('osaca_api/src/api/user/profile_badges/ProfileBadgeAssets.ts', repoRoot);
const sharp = createRequire(new URL('osaca_docs/package.json', repoRoot))('sharp');

const BADGES = {
	staff: 'staff.svg',
	partner: 'partner.svg',
	bug_hunter: 'bug-hunter.svg',
};
const SIZE = 128;

const manifestFile = new URL('manifest.json', badgesDir);
const previous = existsSync(manifestFile) ? JSON.parse(readFileSync(manifestFile, 'utf8')) : {};
const previousAssets = readFileSync(assetsFile, 'utf8');
const manifest = {};

for (const [kind, source] of Object.entries(BADGES)) {
	const svg = readFileSync(new URL(source, badgesDir));
	const png = await sharp(svg).resize(SIZE, SIZE).png().toBuffer();
	const webp = await sharp(svg).resize(SIZE, SIZE).webp({quality: 90}).toBuffer();
	const hash = createHash('sha256').update(png).digest('hex').slice(0, 16);

	const oldHash = previous[kind]?.hash ?? previousAssets.match(new RegExp(`${kind}: '([0-9a-f]{16})'`))?.[1];
	if (oldHash && oldHash !== hash) {
		for (const ext of ['png', 'webp']) {
			rmSync(new URL(`${oldHash}.${ext}`, badgesDir), {force: true});
		}
	}

	writeFileSync(new URL(`${hash}.png`, badgesDir), png);
	writeFileSync(new URL(`${hash}.webp`, badgesDir), webp);
	manifest[kind] = {source, hash};
	console.log(`${kind}: ${hash}`);
}

writeFileSync(manifestFile, `${JSON.stringify(manifest, null, '\t')}\n`);
writeFileSync(
	assetsFile,
	`// SPDX-License-Identifier: AGPL-3.0-or-later

// Generated by tools/branding/render-profile-badges.mjs from osaca_static/badges/*.svg. Do not edit by hand.
export const PROFILE_BADGE_ASSETS = {
${Object.entries(manifest)
	.map(([kind, {hash}]) => `\t${kind}: '${hash}',`)
	.join('\n')}
} as const;
`,
);
